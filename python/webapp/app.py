# --- cache ----------------------------------------------------------------
# Assembling a league is many API calls, so hold it briefly rather than rebuild
# it on every tab switch. Charts are cheap to redraw from the cached frames.
_cache: dict = {}


def league_data(league_id: str, fresh: bool = False) -> dict:
    hit = _cache.get(league_id)
    if hit and not fresh and time.time() - hit["at"] < TTL:
        return hit
    seasons = sm.apply_playoffs(sm.seasons(league_id), PLAYOFF_DIR)
    # Only this league's brackets -- a stored 2025.json belongs to a league, not
    # to the number 2025, so another league must not inherit DDBM's playoffs.
    playoffs = sm.load_playoffs(
        PLAYOFF_DIR, league_ids=[s.league_id for s in seasons.values()])
    d = {"at": time.time(), "seasons": seasons, "playoffs": playoffs,
         "names": list(seasons)}
    _cache[league_id] = d
    return d


def pick(league_id: str, season: str | None, fresh: bool = False):
    d = league_data(league_id, fresh)
    key = season if season in d["seasons"] else d["names"][-1]
    return d, d["seasons"][key], key


def png(fig) -> Response:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight", facecolor="white")
    matplotlib.pyplot.close(fig)
    return Response(buf.getvalue(), media_type="image/png",
                    headers={"Cache-Control": "no-cache"})


# --- chart registry -------------------------------------------------------
# name -> (scope, fn). Season charts take a Season; career/playoff charts take
# the whole league. Everything comes straight from plots.py.
SEASON_CHARTS = {
    "standings": plots.plot_standings, "luck": plots.plot_luck,
    "efficiency": plots.plot_efficiency, "consistency": plots.plot_consistency,
    "pf_pa": plots.plot_pf_pa, "table_position": plots.plot_table_position,
    "team_points": plots.plot_team_points,
    "allplay": plots.plot_allplay, "power_rank": plots.plot_power_rank,
    "manager_profile": plots.plot_manager_profile,
    "position_scoring": plots.plot_position_scoring,
    "roster_heatmap": plots.plot_roster_heatmap,
    "starter_bench": plots.plot_starter_bench,
    "position_box": plots.plot_position_box,
    "roster_counts": plots.plot_roster_counts,
    "trade_performance": plots.plot_trade_performance,
    "waiver_performance": plots.plot_waiver_performance,
}


@app.get("/chart/{name}")
def chart(name: str, league: str = DEFAULT_LEAGUE, season: str | None = None,
          matchup: str | None = None, scope: str = "title", _: str | None = None):
    d, s, key = pick(league, season)
    if name in SEASON_CHARTS:
        return png(SEASON_CHARTS[name](s))
    if name == "career":
        return png(plots.plot_career(d["seasons"]))
    if name == "trajectory":
        return png(plots.plot_trajectory(d["seasons"]))
    if name == "playoff_stats":
        return png(plots.plot_playoff_stats(d["playoffs"], scope))
    if name == "playoff_players":
        return png(plots.plot_playoff_players(d["playoffs"], scope=scope))
    if name == "clutch":
        return png(plots.plot_clutch(d["seasons"], d["playoffs"], scope))
    if name == "bracket":
        p = d["playoffs"].get(key)
        return png(plots.plot_playoff_bracket(p))
    if name == "playoff_matchup":
        p = d["playoffs"].get(key)
        mid = matchup or p.config.get("final")
        return png(plots.plot_playoff_matchup(p, mid))
    return Response(status_code=404)


