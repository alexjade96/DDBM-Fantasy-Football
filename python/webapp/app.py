# A prototype way in that doesn't need the user to already know a league id:
# type a Sleeper username (or numeric user_id), get back every league that
# account is in for a season, and click one to jump to its dashboard (the
# links are the same /league=<id> route the landing form leads to). Sleeper's
# user-leagues endpoint is season-scoped, so `season` is a real control here;
# it defaults to whatever season leagues are currently being played for.
_SLEEPER_CDN = "https://sleepercdn.com/avatars/thumbs/"


def _current_nfl_season() -> str:
    """The season Sleeper considers current (stable through the offseason,
    unlike the week counter). Falls back to a fixed recent year if
    `/state/nfl` can't be reached, so the lookup form still renders."""
    try:
        st = sm.nfl_state() or {}
        return str(st.get("league_season") or st.get("season") or "2025")
    except Exception:
        return "2025"


@app.get("/user-leagues", response_class=HTMLResponse)
def user_leagues(request: Request, user: str = "", season: str | None = None):
    """List the leagues a Sleeper user belongs to for a season (HTMX fragment).

    A blank/unknown handle or a private account is a normal thing to hit, so
    every failure path answers with a message in the results area rather than
    a 500 -- the form stays usable and the query can be retried.
    """
    handle = (user or "").strip()
    if not handle:
        return tpl.TemplateResponse(request, "_user_leagues.html", {
            "error": "Enter a Sleeper username or user ID.", "handle": handle})
    sea = str(season).strip() if season else _current_nfl_season()
    try:
        u = sm.user(handle)
    except Exception:
        u = None
    if not u or not u.get("user_id"):
        return tpl.TemplateResponse(request, "_user_leagues.html", {
            "error": f"No Sleeper user found for “{handle}”.",
            "handle": handle, "season": sea})
    try:
        raw = sm.user_leagues(u["user_id"], sea)
    except Exception:
        return tpl.TemplateResponse(request, "_user_leagues.html", {
            "error": "Couldn’t load this user’s leagues right now. Try again.",
            "handle": handle, "season": sea, "user": u})
    leagues = [{
        "league_id": lg.get("league_id"),
        "name": lg.get("name") or "(unnamed league)",
        "season": lg.get("season") or sea,
        "status": (lg.get("status") or "").replace("_", " "),
        "total_rosters": lg.get("total_rosters"),
        "avatar": (_SLEEPER_CDN + lg["avatar"]) if lg.get("avatar") else None,
    } for lg in raw if lg.get("league_id")]
    uav = u.get("avatar")
    ctx = {
        "handle": handle, "season": sea,
        "user": {
            "user_id": u["user_id"],
            "display_name": u.get("display_name") or u.get("username") or handle,
            "username": u.get("username"),
            "avatar": (_SLEEPER_CDN + uav) if uav else None,
        },
        "leagues": leagues,
        # A few seasons back from the current one, newest first, for the picker.
        "seasons": [str(y) for y in range(int(_current_nfl_season()),
                                          int(_current_nfl_season()) - 8, -1)],
    }
    return tpl.TemplateResponse(request, "_user_leagues.html", ctx)


def _resolve_week(s, week: str | int | None, allow_zero: bool = False) -> int:
    """Clamp a possibly-invalid week param into [1, s.last_week], defaulting to
    the latest -- shared by _week_context() and the scoreboard lazy part (see
    @tab_part("overview"/"weekly", "scoreboard")) so both resolve the exact
    same week from the same raw input.

    `allow_zero` lets the lower bound drop to 0, the Weekly tab's synthetic
    "Pre-season" slot (the draft, not a scored week) -- only passed when the
    season actually has draft data, so week 0 can't be reached otherwise.
    """
    lo = 0 if allow_zero else 1
    wk = s.last_week
    if week is not None and week != "":
        try:
            wk = max(lo, min(int(week), s.last_week))
        except (TypeError, ValueError):
            pass
    return wk


def _week_context(s, week: str | int | None = None,
                  allow_zero: bool = False) -> dict:
    """Everything the current-week view needs EXCEPT the scoreboard itself:
    the selected week (defaulting to the current one) and its KPI tiles.

    Shared by the Weekly tab and the Season overview's lead section so the two
    can't drift -- overview always leads with the current week (week=None), while
    Weekly shows whatever week the rail selected. `wk_games`/`records` (the
    scoreboard's per-game lineup detail and cumulative-record annotations) used
    to live here too, but week_matchups() builds a full lineup/optimal-lineup
    breakdown for every game -- too heavy to sit in front of this section's own
    headline tiles -- so they're now the "scoreboard" lazy part instead (see
    _week_part_scoreboard() below), computed only once that placeholder fires.

    `allow_zero` adds the Weekly tab's synthetic week 0 ("Pre-season", the
    draft) to `weeks` and, when it's the selected week, returns null KPI tiles
    (there is no scored game) -- the template branches on `week == 0` to show
    the draft instead. Only the Weekly TAB passes it; the Overview lead and the
    standalone weekly report never do (they are about a played week).
    """
    wk = _resolve_week(s, week, allow_zero=allow_zero)
    lo = 0 if allow_zero else 1
    weeks = list(range(lo, s.last_week + 1))
    if wk == 0:
        # No scored game in the pre-season slot: every KPI tile is empty and
        # the template shows the draft board / standouts instead. Skip
        # week_stats() entirely rather than call it with an out-of-range week.
        return {
            "week": 0, "weeks": weeks, "current_week": s.current_week,
            "live": s.in_progress, "is_current": False,
            "kpi_top": None, "kpi_blow": None, "kpi_close": None, "kpi_bench": None,
        }
    ws = metrics.week_stats(s, wk)
    decided = ws[ws["result"].isin(["W", "L", "T"])]
    wins = decided[decided["margin"] > 0]
    top = ws.iloc[0] if len(ws) else None
    blow = wins.loc[wins["margin"].idxmax()] if len(wins) else None
    close = wins.loc[wins["margin"].idxmin()] if len(wins) else None
    bench = (ws.loc[ws["left_on_bench"].idxmax()]
             if ws["left_on_bench"].notna().any() else None)
    # {value, user_name} instead of a pre-joined string, so a template can put
    # the manager's portrait (idm.who) next to the figure instead of a bare
    # name -- None when there's no such game, and templates fall back to a dash placeholder.
    def kpi(row, val, fmt):
        return None if row is None else {"value": fmt(row[val]), "user_name": row["user_name"]}

    return {
        "week": wk, "weeks": weeks,
        # Current-week framing: during a live season the view opens on
        # current_week and badges it live; on a finished season `live` is False.
        "current_week": s.current_week, "live": s.in_progress,
        "is_current": wk == s.current_week,
        "kpi_top": kpi(top, "points", lambda v: f"{v:.1f}"),
        "kpi_blow": kpi(blow, "margin", lambda v: f"+{v:.1f}"),
        "kpi_close": kpi(close, "margin", lambda v: f"+{v:.1f}"),
        "kpi_bench": kpi(bench, "left_on_bench", lambda v: f"{v:.1f}"),
    }


# Positions shown as their own count columns in the Week-0 "Drafted Rosters"
# summary row, in scoreboard order (mirrors sortPosition / SLOT_ORDER).
_PRESEASON_POS = ["QB", "RB", "WR", "TE", "K", "DEF"]


def _preseason_rosters(s, board=None) -> list[dict]:
    """The Weekly tab's Week 0 ("Pre-season") view: each member's roster AS
    DRAFTED, one entry per manager, ordered by DRAFT SLOT (manager pick order,
    1..N). Built straight off draft.draft_board() -- one row per pick -- so it
    costs nothing beyond the draft_board() call the Weekly branch already makes
    to gate week 0.

    Returns `[{user_name, slot, pos_counts: {QB: n, ...}, picks: [{pick,
    player_name, player_id, position}]}]`; empty when the season has no draft
    board. `pos_counts` has a key for every position in `_PRESEASON_POS` (0
    when none), plus "OTHER" only when something outside that list was drafted.
    """
    if board is None:
        board = draft.draft_board(s)
    if board.empty:
        return []
    b = board.sort_values("pick_no")
    out = []
    for name, g in b.groupby("user_name", sort=False):
        picks, pos_counts = [], {p: 0 for p in _PRESEASON_POS}
        slot = None
        for _, r in g.iterrows():
            if slot is None and pd_notna(r.get("draft_slot")):
                slot = int(r["draft_slot"])
            rnd = int(r["round"]) if pd_notna(r["round"]) else None
            pir = int(r["pick_in_round"]) if pd_notna(r["pick_in_round"]) else None
            pos = (r["position"] or "").upper() if pd_notna(r["position"]) else ""
            if pos in pos_counts:
                pos_counts[pos] += 1
            elif pos:
                pos_counts["OTHER"] = pos_counts.get("OTHER", 0) + 1
            picks.append({
                "pick": (f"{rnd}.{pir:02d}" if rnd and pir
                         else (str(int(r["pick_no"])) if pd_notna(r["pick_no"]) else "-")),
                "player_name": r["player_name"] if pd_notna(r["player_name"]) else "N/A",
                "player_id": r["player_id"] if pd_notna(r["player_id"]) else None,
                "position": pos,
            })
        out.append({"user_name": name, "slot": slot, "pos_counts": pos_counts,
                    "picks": picks})
    # Manager pick order: by draft slot ascending; a manager with no resolvable
    # slot (shouldn't happen for a real Sleeper draft) sinks to the bottom.
    out.sort(key=lambda e: e["slot"] if e["slot"] is not None else 999)
    return out


def _season_phase(s, d: dict, key: str) -> dict:
    """Which real-world phase this season is in RIGHT NOW: still in its
    regular season, mid-playoffs, or fully complete. Returns at least
    `{"phase": ...}`, plus phase-specific keys (see below).

    `Season.current_week`/`last_week` are deliberately capped to the regular
    season (season.py's `min(lw, pws - 1)`) -- load-bearing for every
    regular-season metric -- so they can't distinguish "mid-playoffs" from
    "regular season just ended." This reads the SAME playoff data the
    Playoffs tab already resolves (`d["playoffs"]`, `sleepermetrics.
    game_log`/`consolation_bracket`) instead of touching `Season` at all, then
    keeps only the rounds that have actually been played (see below) so a
    configured-but-not-started bracket still reads as "regular".
    """
    p = d["playoffs"].get(key)
    title_rounds, played_rounds = [], []
    if p is not None:
        log = sm.game_log(s, p, consolation=sm.consolation_bracket(s, p))
        # `game_log()` appends a group for EVERY configured round, not just the
        # ones that have been played: `playoff()` emits a PENDING result row for
        # every matchup in every round (with the team set to its "W:<id>"
        # advancement ref), `_tag_bracket()` still tags those future rounds
        # `title`, and `game_log()` treats the ref string as a valid side. So a
        # bare bracket config alone would make every round a `title` group and
        # `title_rounds[-1]` would always be the final -- reading as "the
        # playoffs are on, championship round" during the regular season or
        # while round 1 is still being played.
        title_rounds = [g for g in log if g["kind"] in ("title", "mixed")]
        # A round has actually been PLAYED once it has a decided GAME (one whose
        # score is in, so `pending` is False). Byes don't count: a first-round
        # bye resolves structurally from the seeding the moment the bracket is
        # configured, with nothing played. This is what distinguishes "regular
        # season, bracket merely configured" from "postseason under way".
        played_rounds = [
            g for g in title_rounds
            if any(not gm["pending"] for gm in g["games"])]
    if s.status == "complete":
        # `title_rounds` (ALL rounds, not just the last) lets the complete-phase
        # lead recap the whole postseason run instead of freezing on whatever
        # the last regular-season week happened to be.
        return {"phase": "complete", "playoff": p,
                "champion": (p.champion or None) if p else None,
                "title_rounds": title_rounds}
    if played_rounds:
        # The last PLAYED round -- the one just completed (or, if a later round's
        # lineups are in but nobody has been scored yet, still the last one with
        # real results). The user-facing contract for this lead is "last
        # completed week analysis", so it deliberately does not jump ahead to a
        # round that exists only as PENDING placeholders.
        return {"phase": "playoffs", "playoff": p, "current_round": played_rounds[-1]}
    return {"phase": "regular"}


def _playoff_tiles(games: list[dict], lead: tuple | None = None,
                   tail: list[tuple] | None = None,
                   include_margins: bool = True,
                   game_round: dict | None = None) -> list[tuple]:
    """Highest score / Biggest blowout / Closest game tiles from a set of
    `game_log()` games -- shared between the playoffs-phase (current round only)
    and complete-phase (every played round) Overview leads. Same
    `{value, user_name, detail}` shape `_week_context`'s kpi() tiles use, so
    the template's tile loop stays one generic block.

    Every tile here is a genuine superlative. `lead`, if given, is one more
    caller-supplied standout tile placed FIRST (the complete-phase lead passes
    the champion -- the single most important fact once the season is over).
    `tail` is caller-supplied tiles appended AFTER; `include_margins=False`
    drops Biggest blowout / Closest game (the complete-phase lead swaps them
    for consolation-bracket standouts). `game_round` is `{id(game): "Round N"}`
    -- when given, the Highest-score / Biggest-blowout tiles name the round
    the record fell in (via the tile's `detail` field). A caller with nothing
    to add omits it all.
    """
    decided = [g for g in games if not g["pending"]]
    gr = game_round or {}

    def _winner(g):
        return next((sd for sd in g["sides"] if sd["result"] == "W"), g["sides"][0])

    scored = [(sd, g) for g in games for sd in g["sides"] if sd.get("points") is not None]
    top = max(scored, key=lambda t: t[0]["points"]) if scored else None
    tiles = [
        ("Highest score",
         {"value": f"{top[0]['points']:.1f}", "user_name": top[0]["team"],
          "detail": gr.get(id(top[1]))} if top else None,
         "" if lead is not None else "gold"),
    ]
    if include_margins:
        margined = [g for g in decided if g.get("margin") is not None]
        blow = max(margined, key=lambda g: g["margin"]) if margined else None
        close = min(margined, key=lambda g: g["margin"]) if margined else None
        tiles += [
            ("Biggest blowout",
             {"value": f"+{blow['margin']:.1f}", "user_name": _winner(blow)["team"],
              "detail": gr.get(id(blow))} if blow else None, ""),
            ("Closest game",
             {"value": f"+{close['margin']:.1f}", "user_name": _winner(close)["team"],
              "detail": gr.get(id(close))} if close else None, ""),
        ]
    if lead is not None:
        tiles.insert(0, lead)
    if tail:
        tiles += tail
    return tiles


def _overview_insight_rows(s) -> list[dict]:
    """The regular-season takeaways as STANDOUT TILES for the Overview tab --
    the same `.stat` grid every other tab's "standouts" section uses, not one
    run-on markdown sentence per fact and not one wide table.

    Two tile shapes:
      * a SINGLE tile `{label, value, holder, detail, tone}` (just the table
        leader), and
      * a MERGED tile `{label, rows: [{tone, holder, value, detail}, ...]}` for
        each opposed metric (coaching, luck, points allowed, consistency,
        schedule strength) -- the best and worst halves stacked as two mini
        rows inside one tile rather than two separate tiles.

    Tiles are ordered MOST IMPORTANT FIRST: the table leader, then skill
    (coaching), luck, defence, consistency, and schedule. The CHAMPION is
    deliberately NOT here -- it belongs to the season-complete
    postseason-recap tiles up in the lead (see `_playoff_tiles`), not to a
    regular-season summary. The weekly-high-score-crowns and biggest-mover
    tiles were dropped by request.

    Covers the union of the facts that used to be split between
    summaries.summary_season() (rendered here as `| md` prose) and the old
    webapp-only `_overview_insights()` string. summary_season() itself is
    UNTOUCHED -- still parity-mirrored with R and reused by the season /
    weekly reports.

    Returns [] when there's nothing to say (empty/one-week season), so the
    template's `{% if insight_rows %}` skips the section cleanly.
    """
    import pandas as pd

    tiles: list[dict] = []

    def _ok(holder):
        return holder is not None and not (isinstance(holder, float) and pd.isna(holder))

    def tile(label, value, holder, detail, tone=""):
        if _ok(holder):
            tiles.append({"label": label, "value": value, "holder": str(holder),
                          "detail": detail, "tone": tone})

    def merged(label, best, worst):
        """best/worst are (holder, value, detail) triples; either may be None."""
        rows = [{"tone": tone, "holder": str(h), "value": v, "detail": d}
                for tone, trip in (("good", best), ("bad", worst))
                if trip is not None and _ok((h := trip[0]))
                for v, d in [(trip[1], trip[2])]]
        if rows:
            tiles.append({"label": label, "rows": rows})

    st = getattr(s, "standings", None)
    if st is None or not len(st):
        return tiles

    # 1. The table -- leader and last place (the record at both ends).
    lead = st.iloc[0]
    tail = st.iloc[-1]
    merged("The table",
           (lead["user_name"], f"{int(lead['wins'])}-{int(lead['losses'])}",
            f"top of the table, {round(lead['points'])} pts for"),
           (tail["user_name"], f"{int(tail['wins'])}-{int(tail['losses'])}",
            f"bottom of the table, {round(tail['points'])} pts for")
           if len(st) >= 2 else None)

    # 2. Coaching -- skill: how much of the optimal lineup each team started.
    eff = metrics.efficiency(s)
    if len(eff) >= 2:
        best_c, worst_c = eff.iloc[0], eff.iloc[-1]
        merged("Coaching",
               (best_c["user_name"], f"{best_c['eff']:.1f}%", "of the optimal lineup started"),
               (worst_c["user_name"], f"{worst_c['eff']:.1f}%", "of the optimal lineup started"))
    elif len(eff) == 1:
        best_c = eff.iloc[0]
        merged("Coaching",
               (best_c["user_name"], f"{best_c['eff']:.1f}%", "of the optimal lineup started"),
               None)

    # 3. Luck -- wins above/below all-play expectation.
    lk = metrics.luck(s)
    if len(lk) >= 2:
        lucky, unlucky = lk.iloc[0], lk.iloc[-1]
        merged("Luck",
               (lucky["user_name"], f"{lucky['luck']:+.1f}", "wins vs. all-play expectation"),
               (unlucky["user_name"], f"{unlucky['luck']:+.1f}", "wins vs. all-play expectation"))

    # 4. Defence -- points allowed.
    pfa = metrics.points_for_against(s)
    if len(pfa) >= 2:
        stingy = pfa.loc[pfa["pa"].idxmin()]
        leaky = pfa.loc[pfa["pa"].idxmax()]
        merged("Points allowed",
               (stingy["user_name"], f"{round(stingy['pa'])}", "fewest conceded all season"),
               (leaky["user_name"], f"{round(leaky['pa'])}", "most conceded all season"))

    # 5. Consistency -- week-to-week scoring SD.
    cons = metrics.consistency(s)
    if len(cons) >= 2:
        steady, swingy = cons.iloc[0], cons.iloc[-1]
        merged("Consistency",
               (steady["user_name"], f"SD {round(steady['sd'])}", "smallest week-to-week swing"),
               (swingy["user_name"], f"SD {round(swingy['sd'])}", "biggest week-to-week swing"))

    # 6. Schedule strength -- opponents' average scoring. Easiest slate reads
    #    as the "good" half here, matching the pre-merge tile tones (a tough
    #    schedule was tinted bad, like being unlucky).
    sos = metrics.strength_of_schedule(s)
    if len(sos) >= 2:
        hard = sos.loc[sos["sos"].idxmax()]
        easy = sos.loc[sos["sos"].idxmin()]
        merged("Schedule",
               (easy["user_name"], f"{easy['sos']:.1f}", "easiest, opponent pts/week faced"),
               (hard["user_name"], f"{hard['sos']:.1f}", "toughest, opponent pts/week faced"))
    return tiles


def _week_manager_context(s, week: int, manager: str, wk_games: list[dict]) -> dict:
    """One manager's angle on a single week, for the weekly report's scoped view.

    Reuses `wk_games` (metrics.week_matchups' output, already computed by
    `_week_context`) to find their game and its `regret` (the single costliest
    bench call, already computed there too), and `metrics.table_position` --
    already tracked per week for the bump chart -- for how the week moved them
    in the standings. No new metric: this is formatting glue, same as
    `_week_context` itself.
    """
    game = next((g for g in wk_games
                if any(sd["user_name"] == manager for sd in g["sides"])), None)
    mine = theirs = None
    if game is not None:
        mine = next(sd for sd in game["sides"] if sd["user_name"] == manager)
        theirs = next((sd for sd in game["sides"] if sd["user_name"] != manager), None)

    tp = metrics.table_position(s)
    cur = tp[(tp["week"] == week) & (tp["user_name"] == manager)]
    prev = (tp[(tp["week"] == week - 1) & (tp["user_name"] == manager)]
            if week > 1 else tp.iloc[0:0])
    rank = int(cur["table_position"].iloc[0]) if len(cur) else None
    rank_prev = int(prev["table_position"].iloc[0]) if len(prev) else None
    rank_delta = (rank_prev - rank) if (rank is not None and rank_prev is not None) else None
    regret = mine.get("regret") if mine else None
    allplay = metrics.mgr_allplay_snapshot(s, manager, week)

    tiles = []
    if mine is None:
        tiles.append(("Result", "No game", "bye or eliminated"))
    elif theirs is None:
        tiles.append(("Result", f"{mine['points']:.1f}", "no opponent"))
    else:
        res = mine.get("result")
        tiles.append((
            "Result", res if res in ("W", "L", "T") else "N/A",
            f"{mine['points']:.1f}–{theirs['points']:.1f} vs {theirs['user_name']}"))
    if rank is not None:
        if rank_delta is None:
            tiles.append(("Standings", f"#{rank}", "season start"))
        elif rank_delta > 0:
            tiles.append(("Standings", f"↑{rank_delta} → #{rank}", f"from #{rank_prev}"))
        elif rank_delta < 0:
            tiles.append(("Standings", f"↓{-rank_delta} → #{rank}", f"from #{rank_prev}"))
        else:
            tiles.append(("Standings", f"Holding #{rank}", "unchanged"))
    if regret:
        tag = ", would have flipped it" if regret.get("flips") else ""
        tiles.append(("Lineup call", f"-{regret['gain']:.1f} pts",
                      f"started {regret['out']} over {regret['In']}{tag}"))
    elif mine is not None:
        tiles.append(("Lineup call", "Optimal", "nothing left costly on the bench"))
    if allplay:
        aw, al, ad = allplay["allplay_w"], allplay["allplay_l"], allplay["rank_delta"]
        sub = (f"#{allplay['allplay_rank']} all-play, earned" if not ad else
               f"#{allplay['allplay_rank']} all-play, schedule flattered them by {ad}" if ad > 0 else
               f"#{allplay['allplay_rank']} all-play, outplaying their record by {-ad}")
        tiles.append(("All-play", f"{aw}-{al}", sub))

    parts = []
    if mine is None:
        parts.append(f"{manager} had no game in week {week}.")
    elif theirs is not None:
        verb = ("beat" if mine.get("result") == "W" else
                "lost to" if mine.get("result") == "L" else "tied")
        parts.append(f"{manager} {verb} {theirs['user_name']} "
                     f"{mine['points']:.1f}–{theirs['points']:.1f}.")
    if rank is not None and rank_delta:
        drc = "up" if rank_delta > 0 else "down"
        parts.append(f"They moved {drc} {abs(rank_delta)} spot"
                     f"{'s' if abs(rank_delta) != 1 else ''} to #{rank}.")
    elif rank is not None:
        parts.append(f"They're holding #{rank} in the standings.")
    if regret and regret.get("flips"):
        parts.append(f"Starting {regret['In']} over {regret['out']} at "
                     f"{regret['position']} would have flipped the result.")

    return {"mgr_tiles": tiles, "mgr_narrative": " ".join(parts),
            "mgr_game": game, "mine": mine, "theirs": theirs}


def _week_recap(s, week: int, ws) -> dict:
    """The league-wide recap: a short prose lead plus a handful of chips for
    whatever's genuinely new that week.

    Replaces the old bullet list (`weekly.summary_week()` rendered through
    `_md()`), which mostly just restated the four KPI tiles above it in
    sentence form. `weekly.summary_week()` itself is untouched -- it's also
    what the Discord bot posts, and this is a webapp-only presentation
    change, not a rewrite of that shared text.

    `ws` is `week_stats(s, week)`, already computed by `_week_context` --
    reused here instead of refetched. Every fact besides the lead's top
    score/blowout is deliberately checked against the tiles ABOVE it (which
    already cover top score, blowout, closest game, most benched) so nothing
    doubles up between the tiles, the prose, and the chips.
    """
    if not len(ws):
        return {"lead": "", "chips": []}
    top = ws.iloc[0]
    low = ws.iloc[-1]
    decided = ws[ws["result"].isin(["W", "L", "T"])]
    wins = decided[decided["margin"] > 0]
    blow = wins.loc[wins["margin"].idxmax()] if len(wins) else None

    lead = [f"{top['user_name']} posted the week's top score ({top['points']:.1f})"]
    if blow is not None and blow["user_name"] == top["user_name"]:
        lead[-1] += f" in a {blow['margin']:.1f}-point rout"
    lead[-1] += "."

    # Negative facts, gathered per manager -- whoever holds more than one
    # gets a single combined "toughest week" sentence instead of three
    # disconnected bullets that happen to name the same person.
    negs: dict = {}
    negs.setdefault(low["user_name"], []).append(f"posted the week's low score ({low['points']:.1f})")
    bust = ws.loc[ws["left_on_bench"].idxmax()] if ws["left_on_bench"].notna().any() else None
    if bust is not None:
        negs.setdefault(bust["user_name"], []).append(
            f"left {bust['left_on_bench']:.1f} points on the bench")

    tp = metrics.table_position(s)
    cur = tp[tp["week"] == week][["user_name", "table_position"]]
    prev = tp[tp["week"] == week - 1][["user_name", "table_position"]] if week > 1 else tp.iloc[0:0]
    faller = riser = None
    if len(prev):
        m = cur.merge(prev, on="user_name", suffixes=("_cur", "_prev"))
        m["delta"] = m["table_position_prev"] - m["table_position_cur"]
        # +-1 moves happen most weeks and aren't a story -- only a swing of 2+
        # standings spots is worth naming.
        movers = m[m["delta"].abs() >= 2]
        fallers, risers = movers[movers["delta"] < 0], movers[movers["delta"] > 0]
        if len(fallers):
            faller = fallers.loc[fallers["delta"].idxmin()]
            negs.setdefault(faller["user_name"], []).append(
                f"fell from #{int(faller['table_position_prev'])} "
                f"to #{int(faller['table_position_cur'])}")
        if len(risers):
            riser = risers.loc[risers["delta"].idxmax()]

    worst_name, worst_facts = (max(negs.items(), key=lambda kv: len(kv[1]))
                               if negs else (None, []))
    if len(worst_facts) > 1:
        lead.append(f"{worst_name} had the toughest week: "
                    f"{worst_facts[0]}, on top of {', '.join(worst_facts[1:])}.")
    elif worst_facts:
        lead.append(f"{worst_name} {worst_facts[0]}.")

    chips = []
    if low["user_name"] != worst_name:
        chips.append({"icon": "\U0001F4C9", "label": "Low score",
                      "value": f"{low['user_name']} ({low['points']:.1f})"})
    if riser is not None and riser["user_name"] != worst_name:
        chips.append({"icon": "\U0001F4C8", "label": "Biggest riser",
                      "value": f"{riser['user_name']} up from #{int(riser['table_position_prev'])} "
                               f"to #{int(riser['table_position_cur'])}"})
    if faller is not None and faller["user_name"] != worst_name:
        chips.append({"icon": "\U0001F4C9", "label": "Biggest faller",
                      "value": f"{faller['user_name']} down from #{int(faller['table_position_prev'])} "
                               f"to #{int(faller['table_position_cur'])}"})
    # Luck: a win despite losing the all-play field, or a loss despite
    # winning it -- the story the (now-removed-from-default-view) beaten-or-
    # unlucky chart used to tell, still worth a line without the chart.
    tw = s.team_wk[s.team_wk["week"] == int(week)].copy()
    if {"allplay_w", "allplay_l", "result"}.issubset(tw.columns) and len(tw):
        tw["allplay_pct"] = tw["allplay_w"] / (tw["allplay_w"] + tw["allplay_l"]).clip(lower=1)
        lucky = tw[(tw["result"] == "W") & (tw["allplay_pct"] < 0.4)].sort_values("allplay_pct")
        unlucky = tw[(tw["result"] == "L") & (tw["allplay_pct"] > 0.6)].sort_values(
            "allplay_pct", ascending=False)
        if len(lucky):
            r = lucky.iloc[0]
            aw, al = int(r["allplay_w"]), int(r["allplay_l"])
            # aw == 1 is the extreme case -- their score beat only the single
            # worst lineup in the league that week, i.e. they were a hair from
            # having the league's worst score themselves, and won anyway
            # because their actual opponent happened to be that team.
            if aw == 1:
                value = (f"{r['user_name']} won with almost the league's worst score this "
                         f"week; only their opponent scored less")
            else:
                value = (f"{r['user_name']} won despite outscoring only {aw} of {aw + al} teams")
            chips.append({"icon": "\U0001F340", "label": "Luckiest win", "value": value})
        elif len(unlucky):
            r = unlucky.iloc[0]
            aw, al = int(r["allplay_w"]), int(r["allplay_l"])
            # al == 1 is the mirror extreme -- only ONE team in the league
            # outscored them, and it happened to be the one they had to play.
            if al == 1:
                value = (f"{r['user_name']} lost despite having the league's best score this "
                         f"week except for the one team they had to play")
            else:
                value = (f"{r['user_name']} lost despite outscoring {aw} of {aw + al} teams")
            chips.append({"icon": "\U0001F62B", "label": "Unluckiest loss", "value": value})

    return {"lead": " ".join(lead), "chips": chips[:3]}


def _totw_vs_fa(totw: dict | None, fa_best_team: dict | None) -> dict | None:
    """Team of the Week vs. the best available free-agent lineup, slot-
    matched with the same win/loss `cmp` every other lineup comparison in
    this app uses -- the fixed pairing "Best of the Week" shows (see
    _week_best.html). TotW keeps its own `lineup` (rendered via
    _team_of_week.html so its per-player Manager column survives -- a TotW
    lineup mixes players from many different real rosters, unlike a normal
    lineup_table's single side) alongside the FA lineup and both totals, so
    the template needs nothing else from `fa_best_team`.
    """
    if not totw or not totw.get("lineup") or not fa_best_team or not fa_best_team.get("lineup"):
        return None
    totw_pts = {p["slot"]: p["points"] for p in totw["lineup"]}
    fa_pts = {p["slot"]: p["points"] for p in fa_best_team["lineup"]}

    def _cmp(points, opp):
        return None if opp is None else ("up" if points > opp else "down" if points < opp else "even")

    totw_lineup = [dict(p, cmp=_cmp(p["points"], fa_pts.get(p["slot"]))) for p in totw["lineup"]]
    fa_lineup = [dict(p, cmp=_cmp(p["points"], totw_pts.get(p["slot"]))) for p in fa_best_team["lineup"]]
    return {
        "totw": dict(totw, lineup=totw_lineup),
        "fa_lineup": fa_lineup, "fa_total": fa_best_team["total"],
        # Positive = free agents outscored Team of the Week that week.
        "gain": round(fa_best_team["total"] - totw["total"], 1),
    }


def _week_extras(s, week: int, manager: str | None = None) -> dict:
    """The recap, trades/waivers, and free-agent sections shared by the weekly
    report and the Weekly tab (`_week_narrative.html` / `_week_transactions.html`
    / `_week_fa.html`). Kept separate from `_week_context()` -- the Overview
    tab's current-week lead section also calls `_week_context()` and doesn't
    need any of this, so merging in would make every Overview load pay for
    `free_agent_best_team()` etc. for nothing.

    `manager` scopes trades/waivers to their own moves, same as report.py's
    per-manager report; the free-agent sections are league-wide "what if
    against the whole field" content and are dropped (not just filtered) for
    a manager scope -- redundant with their own trades/waivers.
    """
    week_tx = metrics.week_transactions(s, week)
    if manager:
        week_tx = {
            "trades": [d for d in week_tx["trades"]
                      if any(sd["user_name"] == manager for sd in d["sides"])],
            "waivers": [w for w in week_tx["waivers"] if w["user_name"] == manager],
        }
    free_agents = [] if manager else metrics.free_agent_standouts(s, week)
    return {
        "recap": _week_recap(s, week, metrics.week_stats(s, week)),
        "week_tx": week_tx,
        "free_agents": free_agents,
        # Which position tabs actually have entries this week -- a shallow
        # week simply gets fewer tabs rather than an empty one.
        "fa_positions": [p for p in metrics.POSITIONS
                         if any(fa["position"] == p for fa in free_agents)],
        "fa_best_team": None if manager else metrics.free_agent_best_team(s, week),
        # Positional rank for that week ("RB #1", "WR #57") for every player
        # named anywhere on the page -- idm.posrank() looks names up here by
        # player_id.
        "week_pos_ranks": metrics.week_position_ranks(s, week),
    }


