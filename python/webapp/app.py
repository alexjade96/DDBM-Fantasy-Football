def _md(text: str):
    """Render the summaries' small markdown subset (###, -, **bold**, `code`).

    The summaries are generated by us and use exactly these four constructs, so a
    full markdown dependency would be dead weight. The input is html-escaped
    first, so marking the result safe only trusts the tags this function emits --
    never the data.
    """
    import html
    import re

    from markupsafe import Markup
    out, ul = [], False
    for line in html.escape(text or "").splitlines():
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        line = re.sub(r"`(.+?)`", r"<code>\1</code>", line)
        if line.startswith("### "):
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<h3>{line[4:]}</h3>")
        elif line.startswith("- "):
            if not ul:
                out.append("<ul>")
                ul = True
            out.append(f"<li>{line[2:]}</li>")
        elif line.strip():
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<p>{line}</p>")
    if ul:
        out.append("</ul>")
    return Markup("\n".join(out))


tpl.env.filters["md"] = _md


def _playoff_games(p) -> list[dict]:
    """Every game in the bracket, in the order it was played.

    The raw matchup ids sort alphabetically, which is not bracket order once a
    bracket has more than 9 games (R1M10 lands before R1M2) and says nothing
    about rounds. Walk the results frame instead -- the engine emits it round by
    round -- and describe each game well enough to navigate by.
    """
    games, seen = [], set()
    for mid in p.results["matchup_id"]:
        if mid in seen:
            continue
        seen.add(mid)
        rows = p.results[p.results["matchup_id"] == mid]
        sides = [{"team": r["team"], "points": r["points"], "result": r["result"]}
                 for _, r in rows.iterrows() if pd_notna(r["team"])]
        played = [x for x in sides if x["result"] in ("W", "L", "T")]
        winner = next((x["team"] for x in sides if x["result"] == "W"), None)
        first = rows.iloc[0]
        games.append({
            "id": mid,
            "round": first.get("round") or first.get("round_id"),
            "weeks": first.get("weeks"),
            "bracket": first.get("bracket"),
            "sides": sides,
            "winner": winner,
            "played": bool(played),
            # A bye has one side; an undecided game has teams but no result yet.
            "label": " vs ".join(x["team"] for x in sides) if sides else "TBD",
        })
    return games


def pd_notna(v) -> bool:
    import pandas as pd
    return bool(pd.notna(v))


def _grouped_rules(settings: dict) -> list[tuple[str, list[dict]]]:
    """The point-calculation chart as [(group, [rule, ...])], in plain English.

    Sleeper keys the chart by stat code (`bonus_rec_te`); a manager reading why
    they lost should not have to know what that means. statnames does the
    translating -- shared with the R dashboard and parity-checked against it.
    """
    d = sm.scoring_readable(settings)
    return [(g, rows.to_dict("records")) for g, rows in d.groupby("group", sort=False)]

