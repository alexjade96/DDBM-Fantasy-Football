# --- cache ----------------------------------------------------------------
# Assembling a league is many API calls, so hold it briefly rather than rebuild
# it on every tab switch. Charts are cheap to redraw from the cached frames.
_cache: dict = {}

# Ad-hoc bracket cache: a user-supplied / rolled-back bracket, scored once and
# held under a content-addressed token so the tab and its PNG charts (which are
# separate <img> requests that can't carry a POST body) can all reference the
# same Playoff via ?bracket=<token>. Keyed by a hash of the config, so identical
# brackets share a token and it is idempotent; ephemeral (TTL) and per-content,
# so different visitors never clobber each other -- persistence is client-side
# (localStorage + download), the server stays read-only.
_bracket_cache: dict = {}
_BRACKET_TTL = 3600


def _bracket_token(config: dict) -> str:
    import hashlib
    import json as _json
    raw = _json.dumps(config, sort_keys=True, ensure_ascii=False).encode("utf-8")
    return hashlib.sha1(raw).hexdigest()[:16]


def _cache_bracket(config: dict):
    """Score a config into a Playoff and cache it; returns (token, Playoff)."""
    tok = _bracket_token(config)
    hit = _bracket_cache.get(tok)
    if hit and time.time() - hit["at"] < _BRACKET_TTL:
        return tok, hit["playoff"]
    p = sm.playoff(config, validate=False)
    _bracket_cache[tok] = {"config": config, "playoff": p, "at": time.time()}
    return tok, p


def _bracket_from_token(token: str | None):
    """The cached Playoff for a token, or None if absent/expired."""
    hit = _bracket_cache.get(token) if token else None
    if hit and time.time() - hit["at"] < _BRACKET_TTL:
        return hit["playoff"]
    return None


def league_data(league_id: str, fresh: bool = False) -> dict:
    hit = _cache.get(league_id)
    if hit and not fresh and time.time() - hit["at"] < TTL:
        return hit
    seasons = sm.apply_playoffs(sm.seasons(league_id), SEASON_DIR)
    # Only this league's brackets -- a stored 2025.json belongs to a league, not
    # to the number 2025, so another league must not inherit DDBM's playoffs.
    playoffs = sm.load_playoffs(
        SEASON_DIR, league_ids=[s.league_id for s in seasons.values()])
    # Which seasons have a stored (committed) bracket config.
    source = {k: "committed" for k in playoffs}
    # For every OTHER season, fall back to Sleeper's own winners_bracket so the
    # Playoffs tab shows a real bracket instead of the "no bracket yet" prompt.
    # A stored config always wins (e.g. DDBM 2025's custom bracket); a league
    # with none (Coin Flip and FF 2025) gets Sleeper's. Best-effort: if Sleeper
    # holds no coherent bracket for that season, it stays absent and the tab
    # falls back to the prompt exactly as before.
    for k, s in seasons.items():
        if k in playoffs:
            continue
        try:
            cfg = sm.sleeper_bracket(league_id, k)
            if cfg.get("rounds"):
                playoffs[k] = sm.playoff(cfg, validate=False)
                source[k] = "sleeper"
        except Exception:
            pass
    d = {"at": time.time(), "seasons": seasons, "playoffs": playoffs,
         "playoff_source": source, "names": list(seasons)}
    _cache[league_id] = d
    return d


def pick(league_id: str, season: str | None, fresh: bool = False):
    d = league_data(league_id, fresh)
    key = season if season in d["seasons"] else d["names"][-1]
    return d, d["seasons"][key], key


def _base_ctx(league: str, season_key: str, s, theme: str, bracket: str | None,
               scope: str = "title", bust: int = 0) -> dict:
    """The ctx fields every tab (and every lazy tab SECTION, see TAB_PARTS
    below) needs regardless of which one it is -- factored out of tab() so
    tab_part_view() builds the identical base instead of a second, drifting
    copy of it.
    """
    return {"league": league, "season": season_key, "scope": scope, "theme": theme,
            "bust": bust,
            # Available to every tab so season-total views can flag, mid-season,
            # that their figures are through the current week (see _liveband.html).
            "live": s.in_progress, "current_week": s.current_week,
            # Manager team portraits, keyed by user_name (see _ident.html).
            "avatars": _avatar_map(s),
            # A custom / rolled-back bracket token rides on every playoff chart
            # + walk link so the whole tab reflects it (empty = committed bracket).
            "bracket": bracket or ""}


# --- lazy tab sections ------------------------------------------------------
# A tab's genuinely heavy per-manager/per-week computation (roster/coaching
# detail across every manager, a full week's optimal-lineup solves, a draft
# board, ...) used to run inline in tab()'s own response, blocking the WHOLE
# tab's first paint on it. These sections instead render as a placeholder
# (_lazy.html's `lz.lazy()` macro) that htmx fetches on page load, same idea
# as the existing per-chart <img loading="lazy"> skeleton, generalized to
# tables/drilldowns. One shared route + registry below (mirrors SEASON_CHARTS/
# WEEK_CHARTS/MANAGER_CHARTS's "name -> renderer" shape at the top of this
# file) rather than a bespoke endpoint per section -- adding a new lazy
# section later is one @tab_part(...)-decorated function, not a new route.
TAB_PARTS: dict = {}


def tab_part(tab: str, part: str):
    """Registers `fn(request, s, d, key, ctx) -> Response` as the handler for
    GET /tab/<tab>/part/<part>. `ctx` is already seeded via _base_ctx() plus
    whatever scoping params (manager/week/scope) the request carried -- the
    handler only needs to add what its own section computes and return a
    rendered template, same contract every tab() branch already follows.
    """
    def deco(fn):
        TAB_PARTS[(tab, part)] = fn
        return fn
    return deco


@app.get("/tab/{name}/part/{part}", response_class=HTMLResponse)
def tab_part_view(name: str, part: str, request: Request, league: str = DEFAULT_LEAGUE,
                   season: str | None = None, theme: str = "light",
                   manager: str | None = None, week: str | None = None,
                   scope: str = "title", bracket: str | None = None):
    fn = TAB_PARTS.get((name, part))
    if fn is None:
        return HTMLResponse("<p class='empty'>Unknown section.</p>", status_code=404)
    try:
        d, s, key = pick(league, season)
    except Exception:
        return HTMLResponse(
            "<p class='empty'>Couldn&rsquo;t load this section.</p>")
    # Same fallback tab() itself applies: a manager who doesn't exist in this
    # season (stale link, hand-edited URL) scopes back to the whole league
    # rather than a part handler silently filtering everything down to zero.
    if manager and not (s.standings["user_name"] == manager).any():
        manager = None
    ctx = _base_ctx(league, key, s, theme, bracket, scope)
    ctx["manager"] = manager
    ctx["week"] = week
    return fn(request, s, d, key, ctx)


def _pushed(resp, ctx: dict, tab_name: str):
    """Sets HX-Push-Url so a tab/season switch updates the address bar to a
    bookmarkable /dashboard?league=&season=&tab= URL, without changing what
    htmx actually fetched (still /tab/<name> for the fragment). htmx only
    acts on this header for a request whose TRIGGERING element opted into
    hx-push-url (the top tabs nav, the league/season form) -- every other
    request (chart images, in-tab rails like Roster's manager selector or
    Coaching's week rail) simply ignores it, so setting it unconditionally
    here is what keeps this scoped to tab+season and nothing deeper.

    When ctx["boot"] is set (the panel's very first fetch after /dashboard
    rendered its shell instantly, before the real league name/season list
    were known -- see dashboard()), also appends the same out-of-band shell
    sync /load uses on a league switch, so the placeholder title/season
    picker correct themselves the moment real data is available.
    """
    resp.headers["HX-Push-Url"] = (
        f"/dashboard?league={quote(str(ctx['league']))}"
        f"&season={quote(str(ctx['season']))}&tab={tab_name}")
    if ctx.get("boot"):
        oob = tpl.env.get_template("_shell_sync.html").render(
            league_name=ctx["league_name"], seasons=ctx["seasons"], season=ctx["season"])
        resp.body += oob.encode("utf-8")
        resp.headers["content-length"] = str(len(resp.body))
    return resp


# matplotlib's pyplot state is global and not thread-safe, and the chart theme
# is a module-level token that a request flips before drawing -- so every render
# path holds this lock, or two concurrent requests could draw on each other's
# theme (a dark chart saved with a light facecolor, say).
_render_lock = threading.Lock()


def png(fig) -> Response:
    buf = io.BytesIO()
    # Match the saved facecolor to the active theme so a dark chart isn't matted
    # onto a white rectangle. plots.T is already the theme set under the lock.
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight",
                facecolor=plots.T["bg"])
    matplotlib.pyplot.close(fig)
    # Cacheable per (url incl. theme + bust): the browser reuses charts across
    # tab visits instead of re-fetching every switch. `bust` changes on a live
    # re-score, so a refreshed week is never served stale.
    return Response(buf.getvalue(), media_type="image/png",
                    headers={"Cache-Control": "private, max-age=120"})


