def asset_v() -> str:
    """Cache-busting stamp for the static assets (style.css + builder.js).

    Browsers hold onto these hard: a stale stylesheet silently strips the
    report's layout (a grid degrades to run-together text), and a stale
    builder.js silently runs an old bracket editor (its team dropdowns stop
    populating). One `?v=` on both URLs is the newest mtime across both files,
    so editing EITHER is always picked up -- don't narrow this back to one file.
    """
    newest = 0
    for name in ("style.css", "builder.js"):
        try:
            newest = max(newest, int((BASE / "static" / name).stat().st_mtime))
        except OSError:
            pass
    return str(newest)


@app.middleware("http")
async def _stamp_asset_version(request: Request, call_next):
    """Tell an already-open page which stylesheet build the server is on.

    `?v=<mtime>` only helps on a FULL page load, and this is an htmx app: a tab
    click swaps #panel and never re-reads the <link> in <head>. So a page left
    open across a CSS edit keeps serving the old stylesheet indefinitely, and
    markup relying on a new rule renders unstyled -- grid rows collapse to
    inline spans separated by a single space. The client compares this header on
    every swap and re-points the link when it differs.
    """
    resp = await call_next(request)
    resp.headers["X-Asset-V"] = asset_v()
    return resp


def _md(text: str):
    """Render the summaries' small markdown subset (###, -, **bold**, `code`).

    The summaries are generated by us and use exactly these four constructs, so a
    full markdown dependency would be dead weight. The input is html-escaped
    first, so marking the result safe only trusts the tags this function emits --
    never the data.
    """
    import html
    import re

    from markupsafe import Markup
    out, ul = [], False
    for line in html.escape(text or "").splitlines():
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        line = re.sub(r"`(.+?)`", r"<code>\1</code>", line)
        if line.startswith("### "):
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<h3>{line[4:]}</h3>")
        elif line.startswith("- "):
            if not ul:
                out.append("<ul>")
                ul = True
            out.append(f"<li>{line[2:]}</li>")
        elif line.strip():
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<p>{line}</p>")
    if ul:
        out.append("</ul>")
    return Markup("\n".join(out))


tpl.env.filters["md"] = _md


def pd_notna(v) -> bool:
    import pandas as pd
    return bool(pd.notna(v))


def records(df) -> list[dict]:
    """`df.to_dict("records")` with every missing value as None, not NaN.

    Templates guard missing values with `is not none` / `or`, and **pandas NaN
    defeats both** -- it is neither None nor falsey, so the guard passes and the
    cell renders the literal "nan" (or "+nan" once a format string has been
    applied to it). Scrubbing at this boundary is what makes those guards mean
    what they read as, so hand template rows through here rather than calling
    `to_dict` directly.
    """
    import pandas as pd

    def clean(v):
        if v is None:
            return None
        try:
            # Covers NaN, NaT and pd.NA alike; a list/array argument makes
            # pd.isna return an array, whose truth value raises -- keep those.
            return None if pd.isna(v) else v
        except (TypeError, ValueError):
            return v

    return [{k: clean(v) for k, v in row.items()} for row in df.to_dict("records")]


def _avatar_map(s) -> dict:
    """`{user_name: avatar_url}` for a season, so tab tables/tiles can hang a
    manager's team portrait beside their name (the same identity the Career
    Managers panel shows). Reads the season's `accounts` frame -- the account
    avatar, falling back to the custom team picture. Missing/empty avatars are
    simply omitted, so a name with no portrait renders as plain text.
    """
    import pandas as pd
    acc = getattr(s, "accounts", None)
    if acc is None or getattr(acc, "empty", True) or "user_name" not in acc:
        return {}
    out: dict = {}
    for r in acc.itertuples(index=False):
        name = getattr(r, "user_name", None)
        if not (name is not None and pd.notna(name)):
            continue
        for col in ("avatar_url", "team_avatar_url"):
            v = getattr(r, col, None)
            if v is not None and pd.notna(v) and str(v).strip():
                out[str(name)] = str(v)
                break
    return out


def _grouped_rules(settings: dict) -> list[tuple[str, list[dict]]]:
    """The point-calculation chart as [(group, [rule, ...])], in plain English.

    Sleeper keys the chart by stat code (`bonus_rec_te`); a manager reading why
    they lost should not have to know what that means. statnames does the
    translating -- shared with the R dashboard and parity-checked against it.
    """
    d = sm.scoring_readable(settings)
    return [(g, records(rows)) for g, rows in d.groupby("group", sort=False)]


