@app.get("/", response_class=HTMLResponse)
def index(request: Request, league: str = DEFAULT_LEAGUE):
    d = league_data(league)
    return tpl.TemplateResponse(request, "index.html", {
        "tabs": TABS, "league": league,
        "seasons": list(reversed(d["names"])), "season": d["names"][-1],
        "league_name": d["seasons"][d["names"][-1]].name,
    })


@app.get("/load", response_class=HTMLResponse)
def load(request: Request, league: str = DEFAULT_LEAGUE, season: str | None = None):
    """Load a league (or a season of it): overview panel + a refreshed shell.

    A typo'd or private league id is a normal thing for a user to do, so it
    answers with a message in the panel rather than a 500 -- the previous league
    stays on screen and can be typed back.
    """
    try:
        d, s, key = pick(league, season)
    except Exception:
        return HTMLResponse(
            "<p class='empty'>Couldn&rsquo;t load league <code>"
            f"{html_escape(league)}</code>. Check the id is a Sleeper league "
            "that has at least one scored week.</p>")
    ctx = {"league": league, "season": key, "scope": "title", "bust": 0,
           "league_name": s.name, "seasons": list(reversed(d["names"])),
           "summary": summaries.summary_season(s),
           "charts": ["standings", "power_rank", "allplay", "luck"]}
    return tpl.TemplateResponse(request, "load.html", ctx)


@app.get("/tab/{name}", response_class=HTMLResponse)
def tab(name: str, request: Request, league: str = DEFAULT_LEAGUE,
        season: str | None = None, refresh: int = 0, scope: str = "title",
        matchup: str | None = None):
    if refresh:
        scoring.clear_stats_cache()      # a live week must not serve stale points
    try:
        d, s, key = pick(league, season)
    except Exception:
        return HTMLResponse("<p class='empty'>Couldn&rsquo;t load league <code>"
                            f"{html_escape(league)}</code>.</p>")
    ctx = {"league": league, "season": key, "scope": scope,
           "bust": int(time.time()) if refresh else 0}

    if name == "overview":
        ctx["summary"] = summaries.summary_season(s)
        ctx["charts"] = ["standings", "power_rank", "allplay", "luck"]
    elif name == "weekly":
        ctx["charts"] = ["table_position", "team_points"]
    elif name == "coaching":
        ctx["charts"] = ["efficiency", "consistency", "pf_pa"]
    elif name == "roster":
        ctx["charts"] = ["position_scoring", "roster_counts", "roster_heatmap",
                         "starter_bench", "position_box"]
    elif name == "transactions":
        ctx["charts"] = ["manager_profile", "trade_performance", "waiver_performance"]
    elif name == "career":
        ctx["summary"] = summaries.summary_career(d["seasons"])
        ctx["charts"] = ["career", "trajectory"]
        mg = sm.league_accounts(d["seasons"])
        # NaN is TRUTHY in Jinja, so a missing avatar would sail through
        # `{% if m.avatar_url %}` and render src="nan". Hand the template None.
        mg = mg.astype(object).where(mg.notna(), None)
        ctx["managers"] = mg.to_dict("records")
    elif name == "playoffs":
        # The season rail: every season of this league that HAS a stored bracket,
        # so the postseasons can be walked without leaving the tab.
        ctx["bracket_seasons"] = [n for n in d["names"] if n in d["playoffs"]]
        # Walking to another season from in here must also move the header's
        # season picker, or the two disagree about what is on screen.
        ctx["seasons"] = list(reversed(d["names"]))
        p = d["playoffs"].get(key)
        if p is None:
            ctx["missing"] = key
            return tpl.TemplateResponse(request, "tab_playoffs.html", ctx)
        r = p.results
        played = r[r["result"].isin(["W", "L", "T"])]
        top = played.loc[played["points"].idxmax()] if len(played) else None
        blow = played.loc[played["margin"].idxmax()] if len(played) else None

        # Walk the bracket game by game, in the order it was actually played.
        all_games = _playoff_games(p)
        walk = [g for g in all_games if g["played"]]
        ids = [g["id"] for g in walk]
        cur = matchup if matchup in ids else (p.config.get("final")
                                              if p.config.get("final") in ids
                                              else (ids[-1] if ids else None))
        i = ids.index(cur) if cur in ids else -1
        ctx.update({
            "playoff": p,
            "champion": p.champion or "undecided",
            "games": played["matchup_id"].nunique(),
            "top": (f"{top['points']:.1f} · {top['team']}" if top is not None else "—"),
            "blow": (f"+{blow['margin']:.1f} · {blow['team']}" if blow is not None else "—"),
            "walk": walk,
            "matchup": cur,
            "prev": ids[i - 1] if i > 0 else None,
            "next": ids[i + 1] if 0 <= i < len(ids) - 1 else None,
            "step": (i + 1) if i >= 0 else 0,
            "n_steps": len(ids),
            "summary": sm.playoff_summary(p).to_dict("records"),
            "stats": sm.playoff_stats(d["playoffs"], scope).to_dict("records"),
            "rules": _grouped_rules(p.config.get("scoring_settings", {})),
            "n_rules": len(p.config.get("scoring_settings", {})),
        })
        return tpl.TemplateResponse(request, "tab_playoffs.html", ctx)
    else:
        return HTMLResponse("<p class='empty'>Unknown tab.</p>", status_code=404)

    return tpl.TemplateResponse(request, "tab_charts.html", ctx)


@app.get("/report")
def report(league: str = DEFAULT_LEAGUE, season: str | None = None):
    """Generate and download the standalone HTML season report.

    Rendered on demand (it draws ~19 charts), so it takes a few seconds -- the
    file it returns is fully self-contained and needs the server for nothing
    afterwards.
    """
    import tempfile
    d, s, key = pick(league, season)
    tmp = tempfile.NamedTemporaryFile(suffix=".html", delete=False)
    tmp.close()
    sm.season_report(s, tmp.name, seasons=d["seasons"], playoffs=d["playoffs"])
    fname = f"{s.name}_{key}_report.html".replace(" ", "_")
    return FileResponse(tmp.name, media_type="text/html", filename=fname)


