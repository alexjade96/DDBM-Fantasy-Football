"""FastAPI + HTMX dashboard — the Python instance's web app.

Mirrors the R Shiny dashboard (sl_dashboard) tab for tab. Charts are the very
same matplotlib figures the package already renders, streamed as PNG, so the
R<->Python chart mirror and the parity harness keep protecting them -- the web
layer adds no new plotting code.

    python launch.py python dashboard [--port 8000]
    uvicorn webapp.app:app --reload      # from python/
"""
from __future__ import annotations

import io
import os
import time
from pathlib import Path

import matplotlib
from fastapi import FastAPI, Query, Request
from fastapi.responses import HTMLResponse, Response
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates

matplotlib.use("Agg")

import sleepermetrics as sm  # noqa: E402
from sleepermetrics import metrics, plots, scoring, summaries  # noqa: E402

BASE = Path(__file__).resolve().parent
ROOT = BASE.parent.parent                       # repo root
PLAYOFF_DIR = os.environ.get("SLEEPERMETRICS_PLAYOFFS", str(ROOT / "playoffs"))
DEFAULT_LEAGUE = os.environ.get("SLEEPERMETRICS_LEAGUE", "1252770181306929152")
TTL = int(os.environ.get("SLEEPERMETRICS_TTL", "900"))   # cache seasons 15 min

app = FastAPI(title="Sleeper League Analytics")
app.mount("/static", StaticFiles(directory=BASE / "static"), name="static")
tpl = Jinja2Templates(directory=str(BASE / "templates"))


def _md(text: str):
    """Render the summaries' small markdown subset (###, -, **bold**, `code`).

    The summaries are generated by us and use exactly these four constructs, so a
    full markdown dependency would be dead weight. The input is html-escaped
    first, so marking the result safe only trusts the tags this function emits --
    never the data.
    """
    import html
    import re

    from markupsafe import Markup
    out, ul = [], False
    for line in html.escape(text or "").splitlines():
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        line = re.sub(r"`(.+?)`", r"<code>\1</code>", line)
        if line.startswith("### "):
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<h3>{line[4:]}</h3>")
        elif line.startswith("- "):
            if not ul:
                out.append("<ul>")
                ul = True
            out.append(f"<li>{line[2:]}</li>")
        elif line.strip():
            if ul:
                out.append("</ul>")
                ul = False
            out.append(f"<p>{line}</p>")
    if ul:
        out.append("</ul>")
    return Markup("\n".join(out))


tpl.env.filters["md"] = _md

TABS = [
    ("overview", "Season overview"), ("weekly", "Weekly trends"),
    ("coaching", "Coaching & scoring"), ("roster", "Roster & positions"),
    ("transactions", "Transactions"), ("playoffs", "Playoffs"),
    ("career", "Career"),
]

# --- cache ----------------------------------------------------------------
# Assembling a league is many API calls, so hold it briefly rather than rebuild
# it on every tab switch. Charts are cheap to redraw from the cached frames.
_cache: dict = {}


def league_data(league_id: str, fresh: bool = False) -> dict:
    hit = _cache.get(league_id)
    if hit and not fresh and time.time() - hit["at"] < TTL:
        return hit
    seasons = sm.apply_playoffs(sm.seasons(league_id), PLAYOFF_DIR)
    playoffs = sm.load_playoffs(PLAYOFF_DIR)
    d = {"at": time.time(), "seasons": seasons, "playoffs": playoffs,
         "names": list(seasons)}
    _cache[league_id] = d
    return d


def pick(league_id: str, season: str | None, fresh: bool = False):
    d = league_data(league_id, fresh)
    key = season if season in d["seasons"] else d["names"][-1]
    return d, d["seasons"][key], key


def png(fig) -> Response:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=110, bbox_inches="tight", facecolor="white")
    matplotlib.pyplot.close(fig)
    return Response(buf.getvalue(), media_type="image/png",
                    headers={"Cache-Control": "no-cache"})


# --- chart registry -------------------------------------------------------
# name -> (scope, fn). Season charts take a Season; career/playoff charts take
# the whole league. Everything comes straight from plots.py.
SEASON_CHARTS = {
    "standings": plots.plot_standings, "luck": plots.plot_luck,
    "efficiency": plots.plot_efficiency, "consistency": plots.plot_consistency,
    "pf_pa": plots.plot_pf_pa, "table_position": plots.plot_table_position,
    "team_points": plots.plot_team_points,
    "position_scoring": plots.plot_position_scoring,
    "roster_heatmap": plots.plot_roster_heatmap,
    "starter_bench": plots.plot_starter_bench,
    "position_box": plots.plot_position_box,
    "roster_counts": plots.plot_roster_counts,
    "trade_performance": plots.plot_trade_performance,
    "waiver_performance": plots.plot_waiver_performance,
}


@app.get("/chart/{name}")
def chart(name: str, league: str = DEFAULT_LEAGUE, season: str | None = None,
          matchup: str | None = None, _: str | None = None):
    d, s, key = pick(league, season)
    if name in SEASON_CHARTS:
        return png(SEASON_CHARTS[name](s))
    if name == "career":
        return png(plots.plot_career(d["seasons"]))
    if name == "trajectory":
        return png(plots.plot_trajectory(d["seasons"]))
    if name == "playoff_stats":
        return png(plots.plot_playoff_stats(d["playoffs"]))
    if name == "bracket":
        p = d["playoffs"].get(key)
        return png(plots.plot_playoff_bracket(p))
    if name == "playoff_matchup":
        p = d["playoffs"].get(key)
        mid = matchup or p.config.get("final")
        return png(plots.plot_playoff_matchup(p, mid))
    return Response(status_code=404)


# --- pages ----------------------------------------------------------------
@app.get("/", response_class=HTMLResponse)
def index(request: Request, league: str = DEFAULT_LEAGUE):
    d = league_data(league)
    return tpl.TemplateResponse(request, "index.html", {
        "tabs": TABS, "league": league,
        "seasons": list(reversed(d["names"])), "season": d["names"][-1],
        "league_name": d["seasons"][d["names"][-1]].name,
    })


@app.get("/tab/{name}", response_class=HTMLResponse)
def tab(name: str, request: Request, league: str = DEFAULT_LEAGUE,
        season: str | None = None, refresh: int = 0):
    if refresh:
        scoring.clear_stats_cache()      # a live week must not serve stale points
    d, s, key = pick(league, season)
    ctx = {"league": league, "season": key,
           "bust": int(time.time()) if refresh else 0}

    if name == "overview":
        ctx["summary"] = summaries.summary_season(s)
        ctx["charts"] = ["standings", "luck"]
    elif name == "weekly":
        ctx["charts"] = ["table_position", "team_points"]
    elif name == "coaching":
        ctx["charts"] = ["efficiency", "consistency", "pf_pa"]
    elif name == "roster":
        ctx["charts"] = ["position_scoring", "roster_counts", "roster_heatmap",
                         "starter_bench", "position_box"]
    elif name == "transactions":
        ctx["charts"] = ["trade_performance", "waiver_performance"]
    elif name == "career":
        ctx["summary"] = summaries.summary_career(d["seasons"])
        ctx["charts"] = ["career", "trajectory"]
    elif name == "playoffs":
        p = d["playoffs"].get(key)
        if p is None:
            ctx["missing"] = key
            return tpl.TemplateResponse(request, "tab_playoffs.html", ctx)
        r = p.results
        played = r[r["result"].isin(["W", "L", "T"])]
        top = played.loc[played["points"].idxmax()] if len(played) else None
        blow = played.loc[played["margin"].idxmax()] if len(played) else None
        ctx.update({
            "playoff": p,
            "champion": p.champion or "undecided",
            "games": played["matchup_id"].nunique(),
            "top": (f"{top['points']:.1f} · {top['team']}" if top is not None else "—"),
            "blow": (f"+{blow['margin']:.1f} · {blow['team']}" if blow is not None else "—"),
            "matchups": sorted(played["matchup_id"].unique()),
            "matchup": played["matchup_id"].iloc[-1] if len(played) else None,
            "summary": sm.playoff_summary(p).to_dict("records"),
            "stats": sm.playoff_stats(d["playoffs"]).to_dict("records"),
            "rules": sorted(p.config.get("scoring_settings", {}).items()),
        })
        return tpl.TemplateResponse(request, "tab_playoffs.html", ctx)
    else:
        return HTMLResponse("<p class='empty'>Unknown tab.</p>", status_code=404)

    return tpl.TemplateResponse(request, "tab_charts.html", ctx)


@app.get("/health")
def health():
    return {"ok": True, "league": DEFAULT_LEAGUE}
